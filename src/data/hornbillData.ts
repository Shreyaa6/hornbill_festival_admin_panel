export const findIconOption = (iconValueOrId?: string): IconOption | undefined => {
  if (!iconValueOrId) return undefined
  const cleaned = iconValueOrId.trim()
  return (
    iconOptions.find((opt) => opt.value === cleaned) ||
    iconOptions.find((opt) => opt.id === cleaned) ||
    iconOptions.find((opt) => opt.iconUrl === cleaned) ||
    iconOptions.find((opt) => cleaned.includes(opt.id))
  )
}

export const getIconUrl = (iconValueOrId?: string): string => {
  const opt = findIconOption(iconValueOrId)
  if (opt) return opt.iconUrl
  if (iconValueOrId && (iconValueOrId.startsWith('http') || iconValueOrId.startsWith('/'))) {
    return iconValueOrId
  }
  return '/icons/timeline/walking.png'
}

